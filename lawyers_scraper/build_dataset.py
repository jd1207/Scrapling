def export_json(lawyers, path):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(lawyers, f, indent=2, default=str)
    print(f"Saved {len(lawyers)} lawyers to {path}")


def export_csv(lawyers, path):
    if not lawyers:
        return

    # Flatten list fields
    csv_records = []
    for record in lawyers:
        flat = {}
        for key, value in record.items():
            if isinstance(value, list):
                flat[key] = "; ".join(str(v) for v in value)
            else:
                flat[key] = value
        csv_records.append(flat)

    priority_cols = [
        "name", "firm_name", "firm_size", "phone", "email",
        "address", "city", "state", "zip", "website",
        "practice_areas", "years_experience",
        "education", "bar_admissions", "rating", "num_reviews",
        "bio", "sources", "source_urls", "scraped_at",
    ]
    all_cols = set()
    for record in csv_records:
        all_cols.update(record.keys())

    fieldnames = [c for c in priority_cols if c in all_cols]
    fieldnames += sorted(all_cols - set(fieldnames))

    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(csv_records)

    print(f"Exported {len(csv_records)} lawyers to {path}")


def main():
    lawyers = build_dataset()

    # Summary
    nj_count = sum(1 for l in lawyers if l["state"] == "NJ")
    ny_count = sum(1 for l in lawyers if l["state"] == "NY")
    solo_count = sum(1 for l in lawyers if l.get("firm_size") == 1)

    print(f"Total lawyers: {len(lawyers)}")
    print(f"  New Jersey: {nj_count}")
    print(f"  New York: {ny_count}")
    print(f"  Solo practitioners: {solo_count}")
    print(f"  Small firms (2-5): {len(lawyers) - solo_count}")
    print()

    # Cities breakdown
    from collections import Counter
    cities = Counter(l["city"] for l in lawyers)
    print("By city:")
    for city, count in cities.most_common():
        print(f"  {city}: {count}")
    print()

    # Practice areas
    areas = Counter()
    for l in lawyers:
        for a in l.get("practice_areas", []):
            areas[a] += 1
    print("Top practice areas:")
    for area, count in areas.most_common(15):
        print(f"  {area}: {count}")

    # Export
    export_json(lawyers, "lawyers_scraper/output/all_lawyers_merged.json")
    export_csv(lawyers, "lawyers_scraper/output/all_lawyers_merged.csv")


if __name__ == "__main__":
    main()
